package SchoolAct.ACT2;

public class SimpleCalculator {
    public static void main(String[] args) {
        // Variables
        int number1 = 30;
        int number2 = 20;

        // Addition 
        System.out.println(number1 + number2);

        // Subtraction
        System.out.println(number1 - number2);
        
        // Multiplication
        System.out.println(number1 * number2);

        // Division
        System.out.println(number1 / number2);

        // Modulo
        System.out.println(number1 % number2);

        
    }
}
